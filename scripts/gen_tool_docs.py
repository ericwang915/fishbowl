"""Regenerate docs/tools.md from the live MCP tool schemas: python scripts/gen_tool_docs.py"""

import asyncio
from pathlib import Path

from fishbowl.server import mcp

GROUPS = {
    "Desktop": ["computer", "shell", "clipboard_get", "clipboard_set"],
    "Human in the loop": ["view_screen", "handoff", "control_status"],
    "Browser (CDP)": ["browser_open", "browser_read", "browser_elements", "browser_click", "browser_type",
                      "browser_select", "browser_scroll", "browser_press", "browser_overlays", "browser_wait",
                      "browser_tabs", "browser_tab", "browser_back"],
    "Fast execution": ["browser_run"],
    "Chatbot QA": ["chat_ask", "judge_reply", "model_stats"],
    "Accountability": ["audit_log"],
}  # fmt: skip


def typ(p: dict) -> str:
    if "enum" in p:
        return " \\| ".join(f"`{v}`" for v in p["enum"])
    if "anyOf" in p:
        return " \\| ".join(typ(x) for x in p["anyOf"] if x.get("type") != "null") + "?"
    t = p.get("type", "any")
    return f"{typ(p['items'])}[]" if t == "array" and "items" in p else t


async def main():
    tools = {t.name: t for t in await mcp.list_tools()}
    out = [
        "# Tool reference",
        "",
        f"fishbowl exposes **{len(tools)} MCP tools**. Generated by `scripts/gen_tool_docs.py`.",
        "",
    ]
    for group, names in GROUPS.items():
        out.append(f"- **{group}**: " + " · ".join(f"[`{n}`](#{n})" for n in names))
    for group, names in GROUPS.items():
        out += ["", f"## {group}"]
        for n in names:
            t = tools[n]
            schema = getattr(t, "input_schema", None) or t.inputSchema
            props, req = schema.get("properties", {}), set(schema.get("required", []))
            out += ["", f"### `{n}`", "", " ".join((t.description or "").split()), ""]
            if props:
                out += ["| param | type | default |", "|---|---|---|"]
                for k, p in props.items():
                    default = "**required**" if k in req else f"`{p.get('default')!r}`".replace("None", "null")
                    out.append(f"| `{k}` | {typ(p)} | {default} |")
    assert sum(len(v) for v in GROUPS.values()) == len(tools), "a tool is missing from GROUPS"
    Path(__file__).resolve().parent.parent.joinpath("docs", "tools.md").write_text("\n".join(out) + "\n")


asyncio.run(main())
